test('future-time invariant over every hour/minute with seconds and offsets', () => {
  let checks = 0;
  for (const current of ['2026-10-12T15:50', '2026-12-31T23:59', '2028-02-29T00:00']) {
    const now = new Date(new Date(iso(current)).getTime() + 30000);
    for (let hour = 0; hour < 24; hour++) for (const minute of [0, 5, 20, 30, 55, 59]) for (const offset of [0, 5, 60]) {
      const value = parseText(`${hour}:${String(minute).padStart(2, '0')}提醒我吃饭，提前${offset}分钟`, now);
      if (value.remindAt) {
        assert.ok(new Date(value.remindAt).getTime() - value.remindOffsetMinutes * 60000 > now.getTime());
        assert.equal(value.title, '吃饭');
        assert.equal(value.remindOffsetMinutes, offset);
      } else assert.ok(value.parseWarnings.length);
      checks++;
    }
  }
  assert.equal(checks, 1296);
});
